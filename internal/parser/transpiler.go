package parser

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/saviru/spidey/pkg/sandbox"
)

// converts .spidey into .go
func TranspileToGo(modName string, componentName string, rawContent string, appLayout string, components string, globalStyles *strings.Builder) (string, error) {
	parsed, err := Parse(componentName, rawContent)
	if err != nil {
		return "", err
	}

	if parsed.Styles != "" && globalStyles != nil {
		globalStyles.WriteString(parsed.Styles + "\n")
	}

	if parsed.GoLogic != "" {
		if err := sandbox.ValidateFrontmatter(parsed.GoLogic); err != nil {
			return "", fmt.Errorf("[%s] %w", componentName, err)
		}
	}

	re := regexp.MustCompile(`(?s)<([A-Za-z_][a-zA-Z0-9_/-]*)([^>]*)/>`)

	replaceFunc := func(match string) string {
		submatch := re.FindStringSubmatch(match)
		if len(submatch) == 3 {
			compName := submatch[1]
			attrs := submatch[2]
			if strings.Contains(attrs, "client:load") {
				return fmt.Sprintf(`<spidey-island data-component="%s">{{template "%s" .}}</spidey-island>`, compName, compName)
			}
			return fmt.Sprintf(`{{template "%s" .}}`, compName)
		}
		return match
	}

	parsedComponents := re.ReplaceAllStringFunc(components, replaceFunc)
	parsedHTML := re.ReplaceAllStringFunc(parsed.HTML, replaceFunc)

	// Wrap the page content inside the appLayout if it exists
	var finalHTML string
	if appLayout != "" {
		// Convert components inside the layout file
		parsedLayout := re.ReplaceAllStringFunc(appLayout, replaceFunc)

		// Put component definitions outside content block
		finalHTML = parsedLayout + "\n" + parsedComponents + "\n{{define \"content\"}}\n" + parsedHTML + "\n{{end}}"
	} else {
		finalHTML = parsedComponents + "\n" + parsedHTML
	}

	// remove HTML backticks
	safeHTML := strings.ReplaceAll(finalHTML, "`", "` + \"`\" + `")

	var builder strings.Builder
	builder.WriteString("// Code generated by Spidey. DO NOT EDIT.\n")
	builder.WriteString("package pages\n\n")
	builder.WriteString("import (\n\t\"bytes\"\n\t\"html/template\"\n")
	builder.WriteString(fmt.Sprintf("\t\"%s/internal/spidey\"\n", modName))
	if parsed.GoLogic != "" {
		builder.WriteString("\t\"github.com/saviru/spidey/pkg/sandbox\"\n")
	}
	builder.WriteString(")\n\n")

	funcName := "render_" + strings.ReplaceAll(strings.ReplaceAll(strings.ReplaceAll(componentName, "/", "_"), "-", "_"), "[", "_")
	funcName = strings.ReplaceAll(funcName, "]", "_")

	hasRenderFunc := regexp.MustCompile(`\bfunc\s+Render\s*\(`).MatchString(parsed.GoLogic)

	if parsed.GoLogic != "" {
		// Rename func Render(...) to func render_pageName(...)
		renamedLogic := regexp.MustCompile(`\bfunc\s+Render\s*\(`).ReplaceAllString(parsed.GoLogic, "func "+funcName+"(")
		builder.WriteString(renamedLogic + "\n")
	}

	builder.WriteString("func init() {\n")
	builder.WriteString(fmt.Sprintf("\tspidey.Register(\"%s\", func(data interface{}) (string, error) {\n", componentName))

	if hasRenderFunc {
		builder.WriteString(fmt.Sprintf("\t\trenderResult := %s()\n", funcName))
		builder.WriteString("\t\tdata = sandbox.MergeParams(renderResult, data)\n\n")
	}

	builder.WriteString(fmt.Sprintf("\t\ttmpl, err := template.New(\"%s\").Parse(`%s`)\n", componentName, safeHTML))
	builder.WriteString("\t\tif err != nil {\n\t\t\treturn \"\", err\n\t\t}\n")
	builder.WriteString("\t\tvar buf bytes.Buffer\n")
	builder.WriteString("\t\terr = tmpl.Execute(&buf, data)\n")
	builder.WriteString("\t\treturn buf.String(), err\n")
	builder.WriteString("\t})\n")
	builder.WriteString("}\n")

	return builder.String(), nil
}
